"""Section composition: which page sections exist, and their content.

A section model turns parameters into structure: the caller declares
which sections a page has; this module validates that list and renders
each section's markup using only token-driven CSS classes from
render.py. Content is fixed, generic, and deterministic — the product
is the generated system, not the copy.
"""

SECTION_ORDER = ("header", "hero", "features", "pricing", "cta", "footer")
DEFAULT_SECTIONS = "header,hero,features,footer"


def normalize_sections(value):
    """Comma-separated section names -> canonical-order list.

    Unknown names raise ValueError; order is canonical regardless of
    input order (determinism), duplicates collapse.
    """
    parts = [s.strip().lower() for s in str(value).split(",") if s.strip()]
    unknown = [s for s in parts if s not in SECTION_ORDER]
    if unknown:
        raise ValueError("unknown sections %s (allowed: %s)"
                         % (unknown, list(SECTION_ORDER)))
    return [s for s in SECTION_ORDER if s in set(parts)]


def _header():
    return """<nav class="nav"><span class="brand">Northkit</span>
<ul><li><a href="#features">Features</a></li>
<li><a href="#pricing">Pricing</a></li>
<li><a class="btn btn-primary btn-sm" href="#cta">Get started</a></li>
</ul></nav>"""


def _hero():
    return """<section class="hero">
<h1>Ship your product with a system, not a scramble</h1>
<p class="lead">A coherent, accessible design foundation generated from
your parameters. Deterministic, offline, and contrast-checked.</p>
<p class="actions"><a class="btn btn-primary" href="#pricing">Start now</a>
<a class="btn btn-secondary" href="#features">See features</a></p>
</section>"""


def _features():
    cards = "".join("""<div class="feature"><h3>%s</h3><p>%s</p></div>"""
                    % (title, body) for title, body in (
        ("Deterministic", "Same parameters in, same UI out. Forever."),
        ("Accessible by construction", "Every text pair is contrast-checked before it renders."),
        ("Token-driven", "One source of truth from color to spacing to type."),
        ("Zero dependencies", "Python stdlib and one HTML file. Nothing else."),
    ))
    return '<section class="sect" id="features"><h2>Features</h2>' \
           '<div class="grid">%s</div></section>' % cards


def _pricing():
    tiers = ""
    for name, price, blurb, featured in (
            ("Starter", "$0", "One project, community support", False),
            ("Team", "$24", "Unlimited projects, priority support", True),
            ("Studio", "$96", "Shared libraries and review flow", False)):
        cls = "tier featured" if featured else "tier"
        tiers += """<div class="%s"><h3>%s</h3>
<p class="price">%s<span class="per">/mo</span></p><p>%s</p>
<p><a class="btn %s" href="#">Choose %s</a></p></div>""" % (
            cls, name, price, blurb,
            "btn-primary" if featured else "btn-secondary", name)
    return '<section class="sect" id="pricing"><h2>Pricing</h2>' \
           '<div class="grid pricing">%s</div></section>' % tiers


def _cta():
    return """<section class="cta-band" id="cta">
<h2>Generate your system in seconds</h2>
<p class="actions"><a class="btn btn-invert" href="#">Open the playground</a></p>
</section>"""


def _footer():
    return """<footer class="footer">
<span>Generated by uigen. Parameters in, system out.</span>
<span>Deterministic. Offline. Accessible.</span>
</footer>"""


_BUILDERS = {"header": _header, "hero": _hero, "features": _features,
             "pricing": _pricing, "cta": _cta, "footer": _footer}


def render_sections(sections):
    """Canonical-ordered section list -> HTML string."""
    return "\n".join(_BUILDERS[name]() for name in sections)
